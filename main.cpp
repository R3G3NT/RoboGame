int main() {
    Visualizer::InitScreen();

    try {
        std::vector<std::string> level = {
            "##################################################",
            "#.............###.F........#############.........#",
            "#..R.F........###...............#####.......E....#",
            "#.............########..........#####..........~~#",
            "#.....~~~.....................................~~~#",
            "#....~~~~~....................#######.........~~~#",
            "#.....~~~.....................#..F..#...E.....~~~#",
            "#.............###.............#.....#.........~~~#",
            "#.............###.............##...##..........~~#",
            "#..E..........###....E........................####",
            "#.............###.............................####",
            "##################################################"
        };

        GameEngine engine(level[0].size(), level.size());
        engine.LoadLevel(level);
        engine.Run();
    } 
    catch (const std::exception& e) {
        Visualizer::Shutdown();
        return 1;
    }

    Visualizer::Shutdown();
    return 0;
}
